"""Build the synthetic (question, chunk) training / test data for the Q2 embedder.

The questions are NOT generated by an API: they were authored by Claude (the coding assistant) reading each
chunk, 5 per chunk, one per type in `config.QUESTION_TYPES`, and saved to `training_data/raw/batch_XX.jsonl`
(`{"chunk_id": ..., "questions": [{"type": ..., "question": ...}, ...]}`). This script prints chunks for
authoring, then validates / filters the authored questions and writes the train and test files.

    python -m q2_embedder_final.build_training_data dump --start 0 --count 25   # print chunks to author
    python -m q2_embedder_final.build_training_data status                      # authoring coverage
    python -m q2_embedder_final.build_training_data build                       # validate + filter + write files
    python -m q2_embedder_final.build_training_data build --allow-partial       # same, ignoring chunks not yet authored

Outputs in `training_data/`: questions_raw.jsonl, train.jsonl (kept train questions), test.jsonl (all
structurally-valid test questions, with `rt_rank`), dropped.jsonl, split.json, report.md.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter

import numpy as np

from q2_embedder_final import config
from q2_embedder_final.preprocess import Corpus, block_split, load_corpus

RAW_DIR = config.TRAINING_DATA_DIR / "raw"
_WORD = re.compile(r"[A-Za-z0-9][A-Za-z0-9'\-\.§]*")
# Deictic references that only make sense with the chunk in hand ("this passage", "page 5"). Naming a kind of
# filing ("the brief", "the complaint") is fine: it is how a real user would phrase a query.
_DOC_REF = re.compile(
    r"\b(this|that)\s+(document|passage|excerpt|text|chunk|paragraph|section|part|excerpt)\b"
    r"|\bpage\s+\d+|\bp\.\s*\d+|\baccording to the (text|passage|document|excerpt)\b",
    re.IGNORECASE,
)


def _tokens(text: str) -> list[str]:
    return [t.lower().strip(".'-") for t in _WORD.findall(text)]


def _word_count(text: str) -> int:
    return len(text.split())


def _copies_chunk_span(question: str, chunk: str, n: int = config.QA_COPY_NGRAM) -> bool:
    q, c = _tokens(question), _tokens(chunk)
    if len(q) < n:
        return False
    grams = {tuple(c[i : i + n]) for i in range(len(c) - n + 1)}
    return any(tuple(q[i : i + n]) in grams for i in range(len(q) - n + 1))


# ------------------------------------------------------------------------------------------- authoring io
def _load_raw(corpus: Corpus, allow_partial: bool) -> dict[str, list[dict]]:
    ids = set(corpus.chunk_ids)
    raw: dict[str, list[dict]] = {}
    errors: list[str] = []
    for path in sorted(RAW_DIR.glob("*.jsonl")):
        for ln, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip():
                continue
            where = f"{path.name}:{ln}"
            try:
                row = json.loads(line)
            except json.JSONDecodeError as e:
                errors.append(f"{where}: bad JSON ({e})")
                continue
            cid, qs = row.get("chunk_id"), row.get("questions", [])
            if cid not in ids:
                errors.append(f"{where}: unknown chunk_id {cid!r}")
            elif cid in raw:
                errors.append(f"{where}: duplicate chunk_id {cid}")
            types = [q.get("type") for q in qs]
            if sorted(types) != sorted(config.QUESTION_TYPES):
                errors.append(f"{where}: {cid} needs exactly one question per type, got {types}")
            if any(not str(q.get("question", "")).strip() for q in qs):
                errors.append(f"{where}: {cid} has an empty question")
            raw[cid] = qs
    missing = [c for c in corpus.chunk_ids if c not in raw]
    if missing and not allow_partial:
        errors.append(f"{len(missing)} chunks have no questions yet, first: {missing[:5]}")
    if errors:
        sys.exit("validation failed:\n  " + "\n  ".join(errors[:30]))
    return raw


def cmd_dump(corpus: Corpus, split_of: dict[int, str], start: int, count: int) -> None:
    for i in range(start, min(start + count, len(corpus))):
        print(f"### [{i}] {corpus.chunk_ids[i]} | {split_of[i]} | {_word_count(corpus.texts[i])} words")
        print(corpus.texts[i])
        print()


def cmd_status(corpus: Corpus, split_of: dict[int, str]) -> None:
    raw = _load_raw(corpus, allow_partial=True)
    done = [i for i, c in enumerate(corpus.chunk_ids) if c in raw]
    print(f"authored {len(done)}/{len(corpus)} chunks")
    nxt = next((i for i, c in enumerate(corpus.chunk_ids) if c not in raw), None)
    print(f"next unauthored index: {nxt}")


# ------------------------------------------------------------------------------------------------- build
def cmd_build(corpus: Corpus, split_of: dict[int, str], allow_partial: bool, model: str) -> None:
    from q2_embedder_final.embed import DenseEmbedder

    raw = _load_raw(corpus, allow_partial)
    idx_of = {c: i for i, c in enumerate(corpus.chunk_ids)}
    rows: list[dict] = []
    for cid, qs in raw.items():
        for q in qs:
            rows.append({"chunk_id": cid, "qtype": q["type"], "question": " ".join(q["question"].split())})
    for r in rows:
        i = idx_of[r["chunk_id"]]
        r.update(doc_id=str(corpus.doc_ids[i]), split=split_of[i], chunk_text=corpus.texts[i])

    # ---- structural filters (train + test)
    for r in rows:
        r["drop_reason"] = None
        n = _word_count(r["question"])
        if not config.QA_MIN_WORDS <= n <= config.QA_MAX_WORDS:
            r["drop_reason"] = "length"
        elif _DOC_REF.search(r["question"]):
            r["drop_reason"] = "document_reference"
        elif _copies_chunk_span(r["question"], r["chunk_text"]):
            r["drop_reason"] = "copies_chunk_span"

    # ---- embed: questions (+bge query prefix) vs every chunk of the corpus
    emb = DenseEmbedder("baseline", model)
    Q = emb.encode([config.BGE_QUERY_PREFIX + r["question"] for r in rows])
    C = emb.encode(corpus.texts)
    sims = Q @ C.T
    for k, r in enumerate(rows):
        src = idx_of[r["chunk_id"]]
        r["rt_rank"] = int((sims[k] > sims[k, src]).sum()) + 1  # 1 = source chunk is the top hit

    # ---- near-duplicate siblings (keep the earlier question)
    by_chunk: dict[str, list[int]] = {}
    for k, r in enumerate(rows):
        by_chunk.setdefault(r["chunk_id"], []).append(k)
    for ks in by_chunk.values():
        for a in range(len(ks)):
            for b in range(a):
                if rows[ks[a]]["drop_reason"] is None and rows[ks[b]]["drop_reason"] is None \
                        and float(Q[ks[a]] @ Q[ks[b]]) > config.QA_DUP_COSINE:
                    rows[ks[a]]["drop_reason"] = "near_duplicate"

    # ---- round-trip filter: train only
    for r in rows:
        if r["drop_reason"] is None and r["split"] == "train" and r["rt_rank"] > config.QA_ROUNDTRIP_TOP:
            r["drop_reason"] = f"roundtrip_rank_gt_{config.QA_ROUNDTRIP_TOP}"

    kept = [r for r in rows if r["drop_reason"] is None]
    dropped = [r for r in rows if r["drop_reason"] is not None]
    out = config.TRAINING_DATA_DIR
    out.mkdir(parents=True, exist_ok=True)

    def dump(path, items, fields):
        with path.open("w", encoding="utf-8") as f:
            for r in items:
                f.write(json.dumps({k: r[k] for k in fields}, ensure_ascii=False) + "\n")

    fields = ["chunk_id", "doc_id", "qtype", "question", "rt_rank", "chunk_text"]
    with (out / "questions_raw.jsonl").open("w", encoding="utf-8") as f:
        for cid, qs in raw.items():
            f.write(json.dumps({"chunk_id": cid, "split": split_of[idx_of[cid]], "questions": qs},
                               ensure_ascii=False) + "\n")
    dump(out / "train.jsonl", [r for r in kept if r["split"] == "train"], fields)
    dump(out / "test.jsonl", [r for r in kept if r["split"] == "test"], fields)
    dump(out / "dropped.jsonl", dropped, ["chunk_id", "split", "qtype", "question", "rt_rank", "drop_reason"])
    train_idx = [i for i in range(len(corpus)) if split_of[i] == "train"]
    test_idx = [i for i in range(len(corpus)) if split_of[i] == "test"]
    (out / "split.json").write_text(json.dumps({
        "rule": "q2_embedder_final.preprocess.block_split (contiguous blocks of 6 per document, seed 42)",
        "train_chunk_ids": [corpus.chunk_ids[i] for i in train_idx],
        "test_chunk_ids": [corpus.chunk_ids[i] for i in test_idx],
    }, indent=2), encoding="utf-8")
    (out / "report.md").write_text(_report(rows, kept, dropped, corpus, split_of, model), encoding="utf-8")
    print((out / "report.md").read_text(encoding="utf-8"))


def _report(rows, kept, dropped, corpus, split_of, model) -> str:
    L: list[str] = ["# Synthetic question data - build report", ""]
    L += ["**Authorship:** every question was written by Claude (the coding assistant) after reading the chunk; "
          "no LLM API or RAG-system model was used.",
          f"**Round-trip model:** `{model}` with the bge query prefix; rank = position of the source chunk among "
          f"all {len(corpus)} chunks.", ""]
    L += ["## Counts", "", "| split | chunks | questions authored | kept | dropped |", "|---|---|---|---|---|"]
    for sp in ("train", "test"):
        n_chunks = len({r["chunk_id"] for r in rows if r["split"] == sp})
        a = sum(r["split"] == sp for r in rows)
        k = sum(r["split"] == sp for r in kept)
        L.append(f"| {sp} | {n_chunks} | {a} | {k} | {a - k} |")
    L += ["", "## Kept questions by type", "", "| type | train kept / authored | test kept / authored |", "|---|---|---|"]
    for t in config.QUESTION_TYPES:
        cell = []
        for sp in ("train", "test"):
            a = sum(r["split"] == sp and r["qtype"] == t for r in rows)
            k = sum(r["split"] == sp and r["qtype"] == t for r in kept)
            cell.append(f"{k} / {a}")
        L.append(f"| {t} | {cell[0]} | {cell[1]} |")
    L += ["", "## Drop reasons", "", "| reason | train | test |", "|---|---|---|"]
    reasons = sorted({r["drop_reason"] for r in dropped})
    for why in reasons:
        L.append(f"| {why} | {sum(r['split'] == 'train' and r['drop_reason'] == why for r in dropped)} | "
                 f"{sum(r['split'] == 'test' and r['drop_reason'] == why for r in dropped)} |")
    if not reasons:
        L.append("| (none) | 0 | 0 |")
    L += ["", "## Baseline rank of the source chunk (all authored questions)", "",
          "| split | rank 1 | rank <= 3 | rank <= 10 | median rank |", "|---|---|---|---|---|"]
    for sp in ("train", "test"):
        rk = np.array([r["rt_rank"] for r in rows if r["split"] == sp])
        if len(rk):
            L.append(f"| {sp} | {np.mean(rk <= 1):.2f} | {np.mean(rk <= 3):.2f} | {np.mean(rk <= 10):.2f} | "
                     f"{int(np.median(rk))} |")
    per = Counter(r["chunk_id"] for r in kept if r["split"] == "train")
    train_ids = [c for i, c in enumerate(corpus.chunk_ids) if split_of[i] == "train"]
    counts = [per.get(c, 0) for c in train_ids]
    if counts:
        L += ["", "## Kept questions per train chunk", "",
              f"mean {np.mean(counts):.2f}; min {min(counts)}; chunks with < 3 kept: {sum(c < 3 for c in counts)}; "
              f"chunks with 0 kept: {sum(c == 0 for c in counts)}"]
    L += ["", "## Notes", "",
          "- Train questions must pass the round-trip filter (source chunk in the baseline's top "
          f"{config.QA_ROUNDTRIP_TOP}). Test questions are **not** round-trip filtered, so the test set is not "
          "biased toward questions the baseline already answers; `rt_rank` is stored for subset analysis.",
          "- Structural filters (both splits): word count, references to the document itself "
          "(\"this brief\", \"page 5\"), copied 8-token spans, near-duplicate siblings.",
          "- See `dropped.jsonl` for every dropped question with its reason."]
    return "\n".join(L) + "\n"


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    d = sub.add_parser("dump")
    d.add_argument("--start", type=int, default=0)
    d.add_argument("--count", type=int, default=25)
    sub.add_parser("status")
    b = sub.add_parser("build")
    b.add_argument("--allow-partial", action="store_true")
    b.add_argument("--model", default=config.QA_BASELINE_MODEL)
    args = ap.parse_args(argv)

    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    corpus = load_corpus()
    train_idx, test_idx = block_split(corpus)
    split_of = {int(i): "train" for i in train_idx} | {int(i): "test" for i in test_idx}
    if args.cmd == "dump":
        cmd_dump(corpus, split_of, args.start, args.count)
    elif args.cmd == "status":
        cmd_status(corpus, split_of)
    else:
        cmd_build(corpus, split_of, args.allow_partial, args.model)


if __name__ == "__main__":
    main()
